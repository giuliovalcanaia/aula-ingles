-- 8. RPC de atualização de progresso pelo aluno
-- ============================================================
create or replace function public.update_my_progress(p_link_id bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_estudante_id bigint := (select private.current_estudante_id());
  v_turma_id bigint := (select private.current_turma_id());
begin
  if v_estudante_id is null then
    raise exception 'not_a_student' using errcode = '42501';
  end if;

  -- O aluno só pode marcar o link como iniciado. A conclusão e o desbloqueio
  -- são feitos pelo professor, via update direto na tabela.
  if p_status is null or p_status <> 'fazendo' then
    raise exception 'invalid_status' using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.links l
    join public.atividades a on a.id = l.atividade_id
    where l.id = p_link_id
      and a.turma_id = v_turma_id
  ) then
    raise exception 'link_not_in_student_class' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.progresso_estudante p
    where p.estudante_id = v_estudante_id
      and p.link_id = p_link_id
      and p.status in ('aberta', 'fazendo')
  ) then
    raise exception 'link_not_open' using errcode = '42501';
  end if;

  insert into public.progresso_estudante (estudante_id, link_id, status)
  values (v_estudante_id, p_link_id, p_status)
  on conflict (estudante_id, link_id)
  do update set status = excluded.status, updated_at = now();
end;
$$;

revoke all on function public.update_my_progress(bigint, text) from public, anon;
grant execute on function public.update_my_progress(bigint, text) to authenticated;

-- ============================================================
-- 9. Trigger: novo link cria progresso para alunos da turma
-- ============================================================
create or replace function public.create_progress_for_new_link()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.progresso_estudante (estudante_id, link_id, status)
  select
    e.id,
    new.id,
    case
      when new.ordem = (
        select min(l.ordem)
        from public.links l
        where l.atividade_id = new.atividade_id
      ) then 'aberta'
      else 'bloqueada'
    end
  from public.estudantes e
  join public.atividades a on a.turma_id = e.turma_id
  where a.id = new.atividade_id
  on conflict (estudante_id, link_id) do nothing;

  return new;
end;
$$;

revoke all on function public.create_progress_for_new_link() from public, anon, authenticated;

create trigger links_create_progress
after insert on public.links
for each row execute function public.create_progress_for_new_link();

