-- ============================================================
-- 1. Tabelas
-- ============================================================
create table public.professores (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  nome text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.turmas (
  id bigint generated by default as identity primary key,
  professor_id bigint not null references public.professores(id) on delete cascade,
  nome text not null,
  data_realizacao_atividade timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint turmas_id_professor_unique unique (id, professor_id)
);

create table public.pastas (
  id bigint generated by default as identity primary key,
  professor_id bigint not null references public.professores(id) on delete cascade,
  parent_id bigint,
  nome text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pastas_id_professor_unique unique (id, professor_id),
  constraint pastas_parent_same_professor_fk
    foreign key (parent_id, professor_id)
    references public.pastas(id, professor_id)
    on delete cascade
);

create table public.atividades (
  id bigint generated by default as identity primary key,
  professor_id bigint not null references public.professores(id) on delete cascade,
  turma_id bigint not null,
  pasta_id bigint references public.pastas(id) on delete set null,
  titulo text not null,
  subtitulo text,
  codigo_atividade text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint atividades_codigo_unique unique (codigo_atividade),
  constraint atividades_turma_same_professor_fk
    foreign key (turma_id, professor_id)
    references public.turmas(id, professor_id)
    on delete cascade
);

create table public.links (
  id bigint generated by default as identity primary key,
  atividade_id bigint not null references public.atividades(id) on delete cascade,
  ordem integer not null,
  titulo text not null,
  descricao text,
  href text not null,
  created_at timestamptz not null default now(),
  constraint links_atividade_ordem_unique unique (atividade_id, ordem)
);

create table public.estudantes (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  turma_id bigint not null references public.turmas(id) on delete cascade,
  nome text not null,
  codigo_aluno text not null,
  horario_inicio_atividade timestamptz,
  horario_termino_atividade timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint estudantes_turma_codigo_unique unique (turma_id, codigo_aluno)
);

create table public.progresso_estudante (
  estudante_id bigint not null references public.estudantes(id) on delete cascade,
  link_id bigint not null references public.links(id) on delete cascade,
  status text not null default 'bloqueada'
    check (status in ('aberta', 'fazendo', 'concluida', 'bloqueada')),
  pontuacao integer check (pontuacao is null or pontuacao >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (estudante_id, link_id)
);

