-- ============================================================
-- Atividade x turma: aplicações com código e lista de nomes própria
-- ============================================================
-- A atividade é o conteúdo; cada turma que a realiza é uma "aplicação"
-- com código próprio, data, status e lista de nomes/niques.

-- ---------- 1. Remove políticas antigas dependentes de turma ----------
drop policy if exists turmas_student_select on public.turmas;
drop policy if exists atividades_teacher_all on public.atividades;
drop policy if exists atividades_student_select on public.atividades;
drop policy if exists links_student_select on public.links;
drop policy if exists estudantes_teacher_select on public.estudantes;
drop policy if exists estudantes_teacher_update on public.estudantes;
drop policy if exists estudantes_teacher_delete on public.estudantes;
drop policy if exists atividade_senhas_teacher_select on public.atividade_senhas;

-- ---------- 2. Remove estruturas antigas ----------
drop table if exists public.progresso_estudante cascade;
drop table if exists public.estudante_atividade cascade;

alter table public.estudantes
  drop column if exists turma_id,
  drop column if exists codigo_aluno;

alter table public.atividades
  drop column if exists turma_id,
  drop column if exists codigo_atividade,
  drop column if exists data_realizacao;

drop function if exists private.current_turma_id();

-- ---------- 3. Turmas viram catálogo de rótulos do professor ----------
alter table public.turmas
  add constraint turmas_professor_nome_unique unique (professor_id, nome);

-- ---------- 4. Aplicações da atividade ----------
create table public.aplicacoes (
  id bigint generated by default as identity primary key,
  atividade_id bigint not null references public.atividades(id) on delete cascade,
  turma_id bigint not null references public.turmas(id) on delete restrict,
  codigo text not null unique,
  data date,
  status text not null default 'aberta'
    check (status in ('aberta', 'encerrada')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index aplicacoes_atividade_id_idx on public.aplicacoes (atividade_id);
create index aplicacoes_turma_id_idx on public.aplicacoes (turma_id);

create trigger aplicacoes_set_updated_at
before update on public.aplicacoes
for each row execute function public.set_updated_at();

alter table public.aplicacoes enable row level security;

create policy aplicacoes_teacher_all
on public.aplicacoes
for all
to authenticated
using (
  exists (
    select 1
    from public.atividades a
    where a.id = aplicacoes.atividade_id
      and a.professor_id = (select private.current_professor_id())
  )
)
with check (
  exists (
    select 1
    from public.atividades a
    where a.id = aplicacoes.atividade_id
      and a.professor_id = (select private.current_professor_id())
  )
);

revoke all on public.aplicacoes from anon;
grant select, insert, update, delete on public.aplicacoes to authenticated;

-- ---------- 5. Participações (a lista de nomes da turma) ----------
create table public.participacoes (
  id bigint generated by default as identity primary key,
  aplicacao_id bigint not null
    references public.aplicacoes(id) on delete cascade,
  estudante_id bigint not null
    references public.estudantes(id) on delete cascade,
  nome text not null,
  iniciado_em timestamptz not null default now(),
  concluido_em timestamptz,
  unique (aplicacao_id, estudante_id)
);

create index participacoes_aplicacao_id_idx on public.participacoes (aplicacao_id);
create index participacoes_estudante_id_idx on public.participacoes (estudante_id);

alter table public.participacoes enable row level security;

create policy participacoes_student_select
on public.participacoes
for select
to authenticated
using (estudante_id = (select private.current_estudante_id()));

create policy participacoes_teacher_select
on public.participacoes
for select
to authenticated
using (
  exists (
    select 1
    from public.aplicacoes ap
    join public.atividades a on a.id = ap.atividade_id
    where ap.id = participacoes.aplicacao_id
      and a.professor_id = (select private.current_professor_id())
  )
);

revoke all on public.participacoes from anon;
grant select on public.participacoes to authenticated;

create policy aplicacoes_student_select
on public.aplicacoes
for select
to authenticated
using (
  exists (
    select 1
    from public.participacoes p
    where p.aplicacao_id = aplicacoes.id
      and p.estudante_id = (select private.current_estudante_id())
  )
);

-- ---------- 6. Progresso por participação ----------
create table public.progresso_estudante (
  participacao_id bigint not null
    references public.participacoes(id) on delete cascade,
  link_id bigint not null references public.links(id) on delete cascade,
  status text not null default 'bloqueada'
    check (status in ('aberta', 'fazendo', 'concluida', 'bloqueada')),
  pontuacao integer check (pontuacao is null or pontuacao >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (participacao_id, link_id)
);

create index progresso_estudante_link_id_idx
  on public.progresso_estudante (link_id);

create trigger progresso_estudante_set_updated_at
before update on public.progresso_estudante
for each row execute function public.set_updated_at();

alter table public.progresso_estudante enable row level security;

create policy progresso_student_select
on public.progresso_estudante
for select
to authenticated
using (
  exists (
    select 1
    from public.participacoes p
    where p.id = progresso_estudante.participacao_id
      and p.estudante_id = (select private.current_estudante_id())
  )
);

create policy progresso_teacher_select
on public.progresso_estudante
for select
to authenticated
using (
  exists (
    select 1
    from public.participacoes p
    join public.aplicacoes ap on ap.id = p.aplicacao_id
    join public.atividades a on a.id = ap.atividade_id
    where p.id = progresso_estudante.participacao_id
      and a.professor_id = (select private.current_professor_id())
  )
);

create policy progresso_teacher_update
on public.progresso_estudante
for update
to authenticated
using (
  exists (
    select 1
    from public.participacoes p
    join public.aplicacoes ap on ap.id = p.aplicacao_id
    join public.atividades a on a.id = ap.atividade_id
    where p.id = progresso_estudante.participacao_id
      and a.professor_id = (select private.current_professor_id())
  )
)
with check (
  exists (
    select 1
    from public.participacoes p
    join public.aplicacoes ap on ap.id = p.aplicacao_id
    join public.atividades a on a.id = ap.atividade_id
    join public.links l on l.atividade_id = a.id
    where p.id = progresso_estudante.participacao_id
      and l.id = progresso_estudante.link_id
      and a.professor_id = (select private.current_professor_id())
  )
);

grant select, update on public.progresso_estudante to authenticated;
revoke all on public.progresso_estudante from anon;

-- ---------- 7. Políticas de atividades, links e senhas ----------
create policy atividades_teacher_all
on public.atividades
for all
to authenticated
using (professor_id = (select private.current_professor_id()))
with check (
  professor_id = (select private.current_professor_id())
  and (
    pasta_id is null
    or exists (
      select 1
      from public.pastas p
      where p.id = atividades.pasta_id
        and p.professor_id = (select private.current_professor_id())
    )
  )
);

create policy atividades_student_select
on public.atividades
for select
to authenticated
using (
  status = 'publicada'
  and exists (
    select 1
    from public.aplicacoes ap
    join public.participacoes p on p.aplicacao_id = ap.id
    where ap.atividade_id = atividades.id
      and p.estudante_id = (select private.current_estudante_id())
  )
);

create policy links_student_select
on public.links
for select
to authenticated
using (
  exists (
    select 1
    from public.aplicacoes ap
    join public.participacoes p on p.aplicacao_id = ap.id
    where ap.atividade_id = links.atividade_id
      and p.estudante_id = (select private.current_estudante_id())
  )
);

create policy atividade_senhas_teacher_select
on public.atividade_senhas
for select
to authenticated
using (
  exists (
    select 1
    from public.atividades a
    where a.id = atividade_senhas.atividade_id
      and a.professor_id = (select private.current_professor_id())
